#!/usr/bin/env bash
# Builds the MPC WebAssembly module and puts it where its two users load it:
#   src/wallet/mpc/meshport_mpc.wasm (+ .sha256)   app + wallet frame
#   supabase/functions/_shared/mpc/                signing service (Deno):
#     wasmBytes.ts (the module as base64 - Edge Functions deploy code, not
#     loose files), and copies of wasm.ts / protocol.ts.
# Everything it writes is committed, so the app, frame and functions build
# without a Rust toolchain. Rerun after changing mpc/ or those two .ts files;
# src/wallet/mpc/mpc.test.ts fails if any copy is stale.
#
# Needs: rustup target add wasm32-wasip1
set -euo pipefail
cd "$(dirname "$0")"
cargo build --release --locked --target wasm32-wasip1

src=../src/wallet/mpc
fn=../supabase/functions/_shared/mpc
mkdir -p "$fn"

cp target/wasm32-wasip1/release/meshport_mpc.wasm "$src/meshport_mpc.wasm"
sha=$(sha256sum "$src/meshport_mpc.wasm" | cut -d' ' -f1)
echo "$sha" > "$src/meshport_mpc.wasm.sha256"

cp "$src/wasm.ts" "$src/protocol.ts" "$fn/"
{
  echo "// Generated by mpc/build.sh - do not edit. The MPC module as base64."
  echo "export const MPC_WASM_SHA256 = '$sha'"
  printf "export const MPC_WASM_BASE64 = '"
  base64 -w0 "$src/meshport_mpc.wasm"
  echo "'"
} > "$fn/wasmBytes.ts"

echo "built $src/meshport_mpc.wasm ($(wc -c < "$src/meshport_mpc.wasm") bytes, sha256 $sha)"
